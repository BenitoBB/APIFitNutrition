package dto;

import java.util.List;

/**
 * DTO de entrada para la creación de una nueva dieta con sus categorías de horario.
 * RN-16: Mínimo 1 categoría requerida.
 * RN-17: Sin límite máximo de categorías.
 */
public class RQCrearDieta {
    private String nombreDieta;
    private String observaciones;
    private int idMedico;
    private List<String> categorias;

    public RQCrearDieta() {
    }

    public String getNombreDieta() {
        return nombreDieta;
    }

    public void setNombreDieta(String nombreDieta) {
        this.nombreDieta = nombreDieta;
    }

    public String getObservaciones() {
        return observaciones;
    }

    public void setObservaciones(String observaciones) {
        this.observaciones = observaciones;
    }

    public int getIdMedico() {
        return idMedico;
    }

    public void setIdMedico(int idMedico) {
        this.idMedico = idMedico;
    }

    public List<String> getCategorias() {
        return categorias;
    }

    public void setCategorias(List<String> categorias) {
        this.categorias = categorias;
    }
}
