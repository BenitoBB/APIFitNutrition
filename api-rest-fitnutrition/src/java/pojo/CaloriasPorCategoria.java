package pojo;

public class CaloriasPorCategoria {
    private String nombreCategoria;
    private double caloriasCategoria;

    public CaloriasPorCategoria() {}

    public String getNombreCategoria() { return nombreCategoria; }
    public void setNombreCategoria(String nombreCategoria) { this.nombreCategoria = nombreCategoria; }

    public double getCaloriasCategoria() { return caloriasCategoria; }
    public void setCaloriasCategoria(double caloriasCategoria) { this.caloriasCategoria = caloriasCategoria; }
}